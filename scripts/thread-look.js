#!/usr/bin/env node
'use strict';
/**
 * THE THREAD PAGE IN THE STANDARD LOOK (20 Nov 2026).
 *
 * A request's or a change's page (#dev-topic-thread) is drawn in the standard
 * look, and in Standard (WIP), exactly as "Paper, simplified, with brand
 * styling" draws it. That look is a set of rules in public/css/app.css scoped
 * to html[data-skin="brand"], reading its own tokens (--bl-*). This script
 * writes the same rules a second time, scoped to html:not([data-skin]) and to
 * what is inside #dev-topic-thread, into the block between the two markers
 * below (it stands before the looks' compiled section and the brand look's own block), so the two cannot drift: a rule changed under the brand look changes
 * here on the next run, and tests/thread-look.test.js fails until it is run.
 *
 *   node scripts/thread-look.js          rewrite the block
 *   node scripts/thread-look.js --check  exit 1 if the block is out of date
 *
 * How a rule is carried over:
 *   - html[data-skin="brand"]<state> <rest>   becomes
 *     html:not([data-skin])<state> :where(#dev-topic-thread) <rest>
 *     (:where adds no weight, so the rules keep the order they win in).
 *   - a rule on <html> itself (the look's tokens) lands on #dev-topic-thread,
 *     so the tokens are the page's own and reach nothing outside it.
 *   - a rule that already names the thread keeps its selector.
 *   - a rule for <body>, for a direct child of <html>, or for another screen
 *     is left out: it could not match inside the thread.
 */
const fs = require('node:fs');
const path = require('node:path');

const CSS = path.join(__dirname, '..', 'public', 'css', 'app.css');
const FLAG = 'html[data-skin="brand"]';
const STD = 'html:not([data-skin])';
const SCOPE = ':where(#dev-topic-thread)';
const START = '/* ── THE THREAD PAGE IN THE STANDARD LOOK (generated by scripts/thread-look.js; do not edit by hand) ── */';
const END = '/* ── END OF THE THREAD PAGE IN THE STANDARD LOOK. ── */';
const OTHER = /#(platform-|home-|communities-|settings-|admin-|auth-|landing-|profile-|notifications-|messages-screen|ai-|workshop-screen|dev-workshop|dev-kanban|app-list|dev-forum|dev-body|standings-|invite-|waitlist-|legal-|me-|search-|bell-|sheet-)/;

function splitTop(text, ch) {
  const out = []; let depth = 0; let cur = '';
  for (const c of text) {
    if (c === '(' || c === '[') depth += 1;
    else if (c === ')' || c === ']') depth -= 1;
    if (c === ch && depth === 0) { out.push(cur); cur = ''; } else cur += c;
  }
  out.push(cur);
  return out;
}

/** One selector of the brand look, as the standard look's thread page reads it; null when it is left out. */
function twin(one) {
  const t = one.trim();
  if (!t.startsWith(FLAG)) return null;
  let i = FLAG.length; let depth = 0;
  for (; i < t.length; i += 1) {
    const c = t[i];
    if (c === '(' || c === '[') depth += 1;
    else if (c === ')' || c === ']') depth -= 1;
    else if (depth === 0 && (/\s/.test(c) || c === '>' || c === '+' || c === '~')) break;
  }
  const state = t.slice(FLAG.length, i);
  const rest = t.slice(i).trim();
  if (!rest) return `${STD}${state} #dev-topic-thread`;
  if (rest.includes('#dev-topic-thread') || rest.includes('#gc-thread')) return `${STD}${state} ${rest}`;
  if (rest.startsWith('body') || rest.startsWith('>') || rest.startsWith('#app-') || OTHER.test(rest)) return null;
  return `${STD}${state} ${SCOPE} ${rest}`;
}

/** The rules of `css` (comments dropped), each with the at-rules around it. */
function rules(css) {
  const text = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const out = []; const stack = []; let start = 0;
  for (let k = 0; k < text.length; k += 1) {
    const c = text[k];
    if (c === '{') {
      const prelude = text.slice(start, k).trim();
      if (prelude.startsWith('@')) { stack.push(prelude); start = k + 1; continue; }
      const close = text.indexOf('}', k);
      out.push({ at: stack.slice(), selector: prelude, body: text.slice(k + 1, close).trim() });
      k = close; start = k + 1;
    } else if (c === '}') { stack.pop(); start = k + 1; } else if (c === ';' && !stack.length) start = k + 1;
  }
  return out;
}

/**
 * A colour a brand rule writes outright (its repaint of the zinc utilities)
 * becomes a token of the page, declared once at the head of the block and read
 * by name, so no carried rule writes a colour of its own.
 */
function tokenise(body, seen) {
  if (/^\s*--/.test(body) && !/;\s*[a-z]/.test(body.replace(/--[a-z0-9-]+\s*:[^;]*;?/g, ''))) return body;
  return body.split(';').map((decl) => {
    if (/^\s*--/.test(decl)) return decl;
    return decl.replace(/#[0-9a-fA-F]{3,8}\b/g, (hex) => {
      const name = `--thread-${hex.slice(1).toLowerCase()}`;
      seen.set(name, hex);
      return `var(${name})`;
    });
  }).join(';');
}

function generate(css) {
  const outside = css.includes(START) ? css.slice(0, css.indexOf(START)) + css.slice(css.indexOf(END) + END.length) : css;
  const lines = [START, '/*TOKENS*/'];
  const seen = new Map();
  let open = '';
  for (const r of rules(outside)) {
    if (!r.selector.includes(FLAG) || r.at.some((a) => /^@(keyframes|font-face)/.test(a))) continue;
    const twins = splitTop(r.selector, ',').map(twin).filter(Boolean);
    if (!twins.length || !r.body) continue;
    const at = r.at.join(' { ');
    if (at !== open) { if (open) lines.push('}'.repeat(open.split(' { ').length)); if (at) lines.push(`${at} {`); open = at; }
    const pad = open ? '  ' : '';
    lines.push(`${pad}${twins.join(`,\n${pad}`)} { ${tokenise(r.body.replace(/\s+/g, ' '), seen)} }`);
  }
  if (open) lines.push('}'.repeat(open.split(' { ').length));
  lines.push(END);
  const names = [...seen.keys()].sort();
  lines[1] = `/* The colours the carried rules wrote outright, each a token of the page, declared once. */\n${STD} #dev-topic-thread { ${names.map((n) => `${n}: ${seen.get(n)};`).join(' ')} }`;
  return { outside, block: lines.join('\n') };
}

/**
 * The brand look's block runs to the end of the sheet (tests/brand-look.test.js reads it so), and the frame looks'
 * compiled section stands directly before it (tests/looks-css.test.js), so this block stands before that section.
 */
const BRAND_HEADING = '/* looks:begin';

function build(css) {
  const { outside, block } = generate(css);
  const at = outside.indexOf(BRAND_HEADING);
  if (at < 0) throw new Error('app.css: the looks section was not found');
  return `${outside.slice(0, at).replace(/\n+$/, '\n')}${block}\n${outside.slice(at)}`;
}

if (require.main === module) {
  const css = fs.readFileSync(CSS, 'utf8');
  const next = build(css);
  if (process.argv.includes('--check')) {
    if (next !== css) { console.error('public/css/app.css: the thread page block is out of date. Run: node scripts/thread-look.js'); process.exit(1); }
  } else if (next !== css) { fs.writeFileSync(CSS, next); console.log('[thread-look] wrote the block'); } else console.log('[thread-look] up to date');
}

module.exports = { build, generate, twin, START, END };
