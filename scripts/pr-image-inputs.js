'use strict';

// Can this pull request change what an image scan looks at?
//
// The PR gate builds five images and scans each for known-vulnerable packages
// (`--scanners vuln`: the OS packages, the npm packages and the browsers in
// it), and blocks on a finding the PR's base does not have. For a change to
// application code alone the answer is known beforehand: the packages come
// from the Dockerfiles, the lockfiles and the bases, and none of them moved.
// Building four of the images to hear it held every such PR for about 80 s
// after its other checks (60 runs, 23 and 24 Nov 2026), and this rule covers
// 251 of the 300 merges before 24 Nov. Each release still scans the platform
// image it built, and the daily audit (security-audit.yml) every image.
//
// The rule names what is KNOWN not to matter and scans for everything else: a
// path it has not met, an unusual file mode, a package manifest anywhere, a
// script, a workflow, a Dockerfile, or a diff it cannot read. It is never
// asked about the starter image, whose sources are generated by code under
// src/ (services/template.js): that one is always built.
//
//   node scripts/pr-image-inputs.js
//
// reads the pull request's merge commit (HEAD, checked out with its parents)
// against the base it merges into, and writes `scan=true|false` to
// $GITHUB_OUTPUT and the reason to the job summary.

const fs = require('node:fs');
const { execFileSync } = require('node:child_process');

// Directories of application source, with the file types each holds. A type
// not listed scans: a .json, .lock, .txt or binary here may be a manifest or
// an SBOM that a scanner reads.
const CODE = ['js', 'cjs', 'mjs', 'ts', 'tsx', 'css', 'html', 'md', 'sql', 'svg', 'png', 'webp', 'jpg', 'jpeg'];
const CODE_DIRECTORIES = [
  ['src/', CODE],
  ['frontend/src/', CODE],
  ['frontend/@/', CODE],
  ['frontend/locales/', ['json', 'md']],
  ['public/', CODE],
  ['styles/', CODE],
  ['tests/', CODE],
  ['tests/baselines/', ['json']],
  ['docs/', CODE],
  ['.agents/', ['md']],
];
const CODE_FILES = new Set(['server.js', 'dapp.json', 'sql-dynamic-baseline.json', 'src/db/migrations/manifest.json',
  'AGENTS.md', 'README.md', 'SPEC.md', 'TODO']);
// Inside those directories, what comes from elsewhere or names packages.
const NOT_CODE = [
  /(^|\/)(node_modules|vendor|bin)\//,
  /(^|\/)(package(-lock)?|npm-shrinkwrap|composer|bom)\.json$/,
  /\.(spdx|cdx|deps)\.json$/,
];
// Regular files, and the side of an add or a delete that does not exist.
const PLAIN_MODES = new Set(['100644', '100755', '000000']);

/** Is this path known not to change the packages in any scanned image? */
function isCodeOnly(file) {
  if (CODE_FILES.has(file)) return true;
  if (NOT_CODE.some((re) => re.test(file))) return false;
  const extension = /\.([a-z0-9]+)$/.exec(file)?.[1];
  return CODE_DIRECTORIES.some(([directory, types]) => file.startsWith(directory) && types.includes(extension));
}

/**
 * `git diff --raw -z --no-renames --abbrev=40` as `{ file, modes }` entries.
 * Throws on anything it does not read exactly.
 */
function parseRaw(raw) {
  const fields = raw.split('\0');
  if (fields.pop() !== '') throw new Error('the diff did not end where it should');
  const entries = [];
  for (let i = 0; i < fields.length; i += 2) {
    const head = /^:(\d{6}) (\d{6}) [0-9a-f]{40} [0-9a-f]{40} [ACDMTUX]\d*$/.exec(fields[i]);
    const file = fields[i + 1];
    if (!head || !file) throw new Error('the diff has an entry of a shape it should not');
    entries.push({ file, modes: [head[1], head[2]] });
  }
  return entries;
}

/** `{ scan, reason }` for a change's entries. */
function decide(entries) {
  if (!entries.length) return { scan: true, reason: 'The change lists no files.' };
  const odd = entries.find(({ modes }) => modes.some((mode) => !PLAIN_MODES.has(mode)));
  if (odd) return { scan: true, reason: `${odd.file} is not a regular file.` };
  const other = entries.filter(({ file }) => !isCodeOnly(file)).map(({ file }) => file);
  if (other.length) {
    return { scan: true, reason: `${other.slice(0, 5).join(', ')}${other.length > 5 ? ` and ${other.length - 5} more` : ''} may change what the images contain.` };
  }
  return { scan: false, reason: `All ${entries.length} changed file${entries.length === 1 ? ' is' : 's are'} application code; the images keep the packages of the base.` };
}

function changedEntries(git = (args) => execFileSync('git', args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })) {
  // A pull request's merge commit: its first parent is the base it merges into.
  const parents = git(['rev-list', '--parents', '-n', '1', 'HEAD']).trim().split(' ').slice(1);
  if (parents.length !== 2) throw new Error(`HEAD is not a pull request's merge commit (${parents.length} parents)`);
  return parseRaw(git(['diff', '--raw', '-z', '--no-renames', '--abbrev=40', parents[0], 'HEAD']));
}

function main() {
  let decision;
  try { decision = decide(changedEntries()); }
  catch (error) { decision = { scan: true, reason: `The change could not be read (${error.message}).` }; }
  console.log(`scan=${decision.scan}: ${decision.reason}`);
  if (process.env.GITHUB_OUTPUT) fs.appendFileSync(process.env.GITHUB_OUTPUT, `scan=${decision.scan}\n`);
  if (process.env.GITHUB_STEP_SUMMARY) {
    fs.appendFileSync(process.env.GITHUB_STEP_SUMMARY, `${decision.scan ? 'Building and scanning' : 'Not built'}: ${decision.reason}\n`);
  }
}

if (require.main === module) main();

module.exports = { isCodeOnly, parseRaw, decide, changedEntries };
