#!/usr/bin/env node
// Derives tests/baselines/shell-markup.json — the checked-in structural
// baseline the shell-artifact tests compare public/index.html against.
//
// ── Why a JSON baseline instead of an HTML fixture ─────────────────────
//
// Step 1 of the React migration pinned the generated document against a
// byte-copy of the hand-written one (tests/fixtures/pre-migration-index.html)
// and asserted whole-markup parity. Step 2 converts screens deliberately, so
// whole-markup parity is exactly the thing that has to change — but the three
// narrower guarantees that fixture also underwrote must NOT lapse:
//
//   * every element id public/js/** looks up still exists,
//   * every data-* attribute name dapp.json selects on still exists,
//   * the legacy <script> tags still load in their original relative order,
//     and the stylesheet cascade is still native → app → tailwind.
//
// Those three are *sets and lists*, not documents. Freezing them as JSON
// keeps the coverage while letting the markup around them move, and makes
// each later chunk's changes reviewable as a diff of named entries rather
// than a 6,000-line HTML diff. Removals are then recorded deliberately in
// RETIRED_IDS / ADDED_IDS in tests/shell-id-inventory.test.js, and in
// RETIRED_SCRIPTS / ADDED_SCRIPTS in tests/shell-script-order.test.js.
//
// ── Running it ─────────────────────────────────────────────────────────
//
// It was run ONCE, against the pre-migration fixture, and that output is the
// committed baseline; the fixture was deleted in the same commit. It is kept
// here so a DELIBERATE refresh is a reviewable command rather than a hand
// edit:
//
//   node scripts/derive-shell-baseline.js --from public/index.html
//
// Refreshing wholesale defeats the point — it makes whatever the shell
// currently emits correct by definition. Prefer recording the delta in the
// RETIRED_*/ADDED_* maps; refresh only when a chunk's churn has made those
// maps longer than the baseline itself, and say so in the commit message.

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const { idsOf, scriptsOf, stylesheetsOf, tokenize } = require(
  path.join(ROOT, 'tests', 'helpers', 'html-tokens'),
);

const OUTPUT = path.join('tests', 'baselines', 'shell-markup.json');

// data-* attribute NAMES actually used on elements. Deliberately not a raw
// text search: `data-panel-slot`, for one, appears only inside an explanatory
// HTML comment — home.js plants those hosts at runtime — and a text search
// would call it present in a document that never had it.
function dataAttrsUsed(html) {
  const names = new Set();
  for (const t of tokenize(html)) {
    if (t.kind !== 'open') continue;
    for (const a of t.attrs) {
      const n = a.name.toLowerCase();
      if (n.startsWith('data-')) names.add(n);
    }
  }
  return [...names].sort();
}

function duplicateIds(ids) {
  const seen = new Map();
  for (const id of ids) seen.set(id, (seen.get(id) || 0) + 1);
  return Object.fromEntries([...seen.entries()].filter(([, n]) => n > 1).sort());
}

function derive(html, source) {
  const ids = idsOf(html);
  return {
    $comment:
      'GENERATED by scripts/derive-shell-baseline.js — the frozen structural baseline for the '
      + 'platform shell. Do not hand-edit: record deliberate changes in the RETIRED_*/ADDED_* maps '
      + 'in tests/shell-id-inventory.test.js and tests/shell-script-order.test.js instead.',
    derivedFrom: source,
    // Document order, duplicates included — the duplicate count is itself
    // pinned (see KNOWN_DUPLICATE_IDS) so it can only ever go down.
    ids,
    duplicateIds: duplicateIds(ids),
    dataAttributes: dataAttrsUsed(html),
    // Every <script src> in document order. The React entry is not in here:
    // the baseline was taken from the pre-React document.
    scripts: scriptsOf(html).filter((s) => s.src).map((s) => s.src),
    stylesheets: stylesheetsOf(html),
  };
}

function main(argv) {
  const fromIdx = argv.indexOf('--from');
  const rel = fromIdx === -1
    ? path.join('tests', 'fixtures', 'pre-migration-index.html')
    : argv[fromIdx + 1];
  if (!rel) {
    console.error('usage: node scripts/derive-shell-baseline.js [--from <html file>]');
    process.exit(1);
  }
  const abs = path.join(ROOT, rel);
  if (!fs.existsSync(abs)) {
    console.error(
      `[derive-shell-baseline] ${rel} does not exist. The pre-migration fixture was deleted when `
      + 'the baseline replaced it — pass --from public/index.html for a deliberate refresh.',
    );
    process.exit(1);
  }
  const baseline = derive(fs.readFileSync(abs, 'utf8'), rel);
  const out = path.join(ROOT, OUTPUT);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, `${JSON.stringify(baseline, null, 2)}\n`);
  console.log(
    `[derive-shell-baseline] wrote ${OUTPUT}: ${baseline.ids.length} ids, `
    + `${baseline.dataAttributes.length} data-* names, ${baseline.scripts.length} scripts`,
  );
}

if (require.main === module) main(process.argv.slice(2));

module.exports = { derive, dataAttrsUsed, duplicateIds };
