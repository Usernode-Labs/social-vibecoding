/** Every emoji once, for search and for naming a recent one. */
export const ALL_EMOJI: readonly EmojiEntry[] = (() => {
  const seen = new Set<string>();
  const all: EmojiEntry[] = [];
  for (const category of EMOJI_CATEGORIES) {
    for (const entry of category.emoji) {
      if (seen.has(entry.emoji)) continue;
      seen.add(entry.emoji);
      all.push(entry);
    }
  }
  return all;
})();

const BY_EMOJI = new Map(ALL_EMOJI.map((entry) => [entry.emoji, entry]));

/** The spoken name of an emoji, for an aria-label: "thumbs up". */
export function emojiName(emoji: string): string {
  if (typeof window !== 'undefined') void ensureNamespace('emoji').catch(() => {});
  return BY_EMOJI.get(emoji)?.name || emoji;
}

/**
 * The emoji whose terms contain every word of the query, in picker order.
 * An empty query matches nothing: the picker shows its categories instead.
 */
export function searchEmoji(query: string, limit = 64): EmojiEntry[] {
  const words = query.toLowerCase().trim().split(/\s+/).filter(Boolean);
  if (!words.length) return [];
  const hits: EmojiEntry[] = [];
  for (const entry of ALL_EMOJI) {
    if (words.every((word) => entry.terms.includes(word))) hits.push(entry);
    if (hits.length >= limit) break;
  }
  return hits;
}
