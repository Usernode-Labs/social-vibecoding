import { t as tr, ensureNamespace } from "../../lib/i18n/runtime";
/**
 * The emoji the reaction picker offers (#2387), by category, each with the
 * words its search matches: the Unicode name, plus a few everyday aliases for
 * the ones people reach for (`+1`, `lol`, `tada`, `thanks`).
 *
 * The set and its order are the app chat's grid (public/js/group-chat.js,
 * GRID_REACTIONS), so both surfaces offer the same emoji. No emoji library:
 * the shell loads no cross-origin assets, and a picker needs names, not the
 * several hundred kilobytes of skin tones and sprite sheets a library brings.
 */

export interface EmojiEntry {
  emoji: string;
  /** What a screen reader says for it: "thumbs up". */
  name: string;
  /** Lower-case words the search matches: the name, the Unicode name, aliases. */
  terms: string;
}

export interface EmojiCategory {
  id: string;
  label: string;
  emoji: EmojiEntry[];
}

function entries(rows: ReadonlyArray<readonly [string, string, string]>): EmojiEntry[] {
  return rows.map(([emoji, name, terms]) => ({
    emoji, get name() { return tr(name); },
    // Keep English aliases searchable alongside the selected language.
    get terms() { return `${terms} ${tr(name).toLocaleLowerCase()}`; },
  }));
}

